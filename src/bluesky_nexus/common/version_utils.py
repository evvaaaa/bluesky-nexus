"""Utilities for Git branch and package version logging.

This module provides utilities to determine the current Git branch, get
the package version, and log version/branch information using the
package logger.
"""

import subprocess

from bluesky_nexus.common.logging_utils import logger


def get_git_branch(default: str = "unknown") -> str:
    """Return the current Git branch name.

    Attempts to query the current Git branch using `git rev-parse`.
    Returns 'default' if Git is not available or an error occurs.

    Returns:
        str: The current Git branch name, or 'unknown' on failure.
    """
    try:
        return (
            subprocess.check_output(
                ["git", "rev-parse", "--abbrev-ref", "HEAD"],
                stderr=subprocess.DEVNULL,
            )
            .decode()
            .strip()
        )
    except (subprocess.CalledProcessError, FileNotFoundError, OSError):
        return default


def get_package_version(default: str = "unknown") -> str:
    """Return the package version string.

    Obtains the version from the dynamically generated `_version.py`
    created by setuptools-scm. Returns 'unknown' if unavailable.

    Returns:
        str: The package version, or 'default' if not found.
    """
    try:
        # Import generated by setuptools-scm during build
        # pylint: disable=import-outside-toplevel
        from bluesky_nexus._version import version as _package_version

        return _package_version
    except ImportError:
        return default


def log_package_info():
    """Log the package version and current Git branch."""
    logger.info(
        "Package version: %s, Git branch: %s",
        get_package_version(),
        get_git_branch(),
    )
