"""Package version logging.

This module provides a helper function for reporting the version of the
``bluesky_nexus`` package. The version string is retrieved from the file
generated by ``setuptools_scm`` and logged through the package logger.

Functions
---------
log_package_version()
    Log the package name and version using the configured logger.
"""

from bluesky_nexus._version import __version__
from bluesky_nexus.common.logging_utils import logger

PACKAGE_NAME = __name__.split(".", maxsplit=1)[0]  # gives "bluesky_nexus"


def log_package_version():
    """Log the package name and version.

    Notes
    -----
    This function retrieves the version string of the ``bluesky_nexus`` package
    (as generated by ``setuptools_scm``) and logs it using the configured logger.
    It does not return a value.
    """
    logger.debug("%s version: %s", PACKAGE_NAME, __version__)
