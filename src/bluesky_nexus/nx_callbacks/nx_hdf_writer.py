import os
import time
from datetime import datetime
from pathlib import Path

from event_model import RunStart
from nexusformat import nexus

from bluesky_nexus.logger import LOGGER

from ._callback import BlueskyNexusCallback

NX_FILE_EXTENSION = ".nxs"


def _validate_directory(path: str | Path, name: str) -> Path:
    """Validate that ``path`` exists, is a directory, and is writable.

    Parameters
    ----------
    path : str or pathlib.Path
        Path to validate.

    Returns
    -------
    pathlib.Path
        Normalized and validated path.

    Raises
    ------
    ValueError
        If the directory does not exist, is not a directory,
        or is not writable.
    """
    p = Path(path)

    if not p.exists():
        raise ValueError(f"{name} does not exist: {path}.")

    if not p.is_dir():
        raise ValueError(f"{name} exists but is not a directory: {p}")

    if not os.access(str(p), os.W_OK):
        raise ValueError(f"{name} is not writable: {p}")

    return p


def _create_nx_file_path(root_directory: Path, start: RunStart) -> Path:
    """Builds the hierarchical directory structure and the final
     NeXus filename using metadata from the start document. It ensures that all
     directories exist and that the filename adheres to the naming scheme used
     by the NexusWriter.

     Directory layout:
         {root_directory}/{project_name}/{sub_project_name}/
         {root_directory}/{project_name}/
         {root_directory}/

    The file name is generated automatically from the run start plan name and
    plan start time.
    """
    # Extract 'project_name' and 'sub_project_name' from metadata passed to the run
    project_name = start.get("project_name")
    sub_project_name = start.get("sub_project_name")

    dir_path: Path = root_directory
    if isinstance(project_name, str) and project_name.strip():
        dir_path = dir_path / project_name.strip()

        if isinstance(sub_project_name, str) and sub_project_name.strip():
            dir_path = dir_path / sub_project_name.strip()
        elif sub_project_name is not None:
            LOGGER.info(
                "Run %s contained sub_project_name=%r, but it was not a "
                "non-empty string. Writing under project directory %s only.",
                start.get("uid"),
                sub_project_name,
                dir_path,
            )
    elif project_name is not None:
        LOGGER.info(
            "Run %s contained project_name=%r, but it was not a non-empty string. "
            "Writing under root output directory %s.",
            start.get("uid"),
            project_name,
            dir_path,
        )
    else:
        LOGGER.debug(
            "Run %s did not contain project_name. Writing under root output directory %s.",
            start.get("uid"),
            dir_path,
        )

    # Create the directories if they do not exist
    dir_path.mkdir(parents=True, exist_ok=True)

    file_name = (
        f"{datetime.fromtimestamp(float(start['time'])).strftime('%Y-%m-%d-%H-%M-%S')}-"
        f"{start.get('plan_name', 'plan-name-not-included')}"
    )
    file_name = f"{file_name.lstrip(NX_FILE_EXTENSION)}{NX_FILE_EXTENSION}"

    return dir_path / file_name


class NexusHdfWriterCallback(BlueskyNexusCallback):
    """A callback which generates .nxs hdf5 files from bluesky documents."""

    def __init__(self, output_root_directory: Path = Path(".")) -> None:
        """Pass the root directory path which the writer will dump nexus files to."""
        super().__init__()
        self.OUTPUT_ROOT_DIRECTORY = _validate_directory(
            output_root_directory, "Output root directory"
        )
        self._current_output_path: Path | None = None

    def process_nexus_structure(self, generated_structure: nexus.NXroot) -> None:
        """This method is called by `NexusCallback` to dump the
        nexus files generated by nexus callback to file.
        """
        if (
            (entry := generated_structure.get("entry", {}))
            and (run_info := entry.get("run_info", {}))
            and (run_start := run_info.get("run_start"))
        ):
            self._write_to_file(
                _create_nx_file_path(self.OUTPUT_ROOT_DIRECTORY, run_start), generated_structure
            )

    def _write_to_file(self, output_path: Path, nexus_root: nexus.NXroot) -> None:
        start_time = time.perf_counter()
        nexus_root.save(output_path)
        LOGGER.info(f"Wrote to file in {time.perf_counter() - start_time}s.")
